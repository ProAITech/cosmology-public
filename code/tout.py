"""Tout, Pols, Eggleton & Han (1996) ZAMS luminosity and radius as functions of mass and metallicity.
Each coefficient = a + b lz + c lz^2 + d lz^3 + e lz^4, lz = log10(Z/0.02)."""
import numpy as np
LC = {'alpha':(0.39704170,-0.32913574,0.34776688,0.37470851,0.09011915),
      'beta':(8.52762600,-24.41225973,56.43597107,37.06152575,5.45624060),
      'gamma':(0.00025546,-0.00123461,-0.00023246,0.00045519,0.00016176),
      'delta':(5.43288900,-8.62157806,13.44202049,14.51584135,3.39793084),
      'epsilon':(5.56357900,-10.32345224,19.44322980,18.97361347,4.16903097),
      'zeta':(0.78866060,-2.90870942,6.54713531,4.05606657,0.53287322),
      'eta':(0.00586685,-0.01704237,0.03872348,0.02570041,0.00383376)}
RC = {'theta':(1.71535900,0.62246212,-0.92557761,-1.16996966,-0.30631491),
      'iota':(6.59778800,-0.42450044,-12.13339427,-10.73509484,-2.51487077),
      'kappa':(10.08855000,-7.11727086,-31.67119479,-24.24848322,-5.33608972),
      'lam':(1.01249500,0.32699690,-0.00923418,-0.03876858,-0.00412750),
      'mu':(0.07490166,0.02410413,0.07233664,0.03040467,0.00197741),
      'nu':(0.01077422,0.0,0.0,0.0,0.0),
      'xi':(3.08223400,0.94472050,-2.15200882,-2.49219496,-0.63848738),
      'omicron':(17.84778000,-7.45345690,-48.96066856,-40.05386135,-9.09331816),
      'pi':(0.00022582,-0.00186899,0.00388783,0.00142402,-0.00007671)}
def _c(t, lz): return sum(t[i]*lz**i for i in range(5))
def L(M, Z=0.02):
    lz = np.log10(Z/0.02); c = {k:_c(v,lz) for k,v in LC.items()}
    return (c['alpha']*M**5.5+c['beta']*M**11)/(c['gamma']+M**3+c['delta']*M**5+c['epsilon']*M**7+c['zeta']*M**8+c['eta']*M**9.5)
def R(M, Z=0.02):
    lz = np.log10(Z/0.02); c = {k:_c(v,lz) for k,v in RC.items()}
    return (c['theta']*M**2.5+c['iota']*M**6.5+c['kappa']*M**11+c['lam']*M**19+c['mu']*M**19.5)/(c['nu']+c['xi']*M**2+c['omicron']*M**8.5+M**18.5+c['pi']*M**19.5)
def Teff(M, Z=0.02): return 5772*(L(M,Z)/R(M,Z)**2)**0.25
if __name__ == '__main__':
    assert abs(L(1.0)-0.698)<0.002 and abs(R(1.0)-0.888)<0.002
